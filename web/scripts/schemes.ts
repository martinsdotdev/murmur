/**
 * Generates src/styles/schemes.css: the app's colour schemes and its pure
 * black night, from the Amber tokens in tailwind.css and m3-colors.css.
 *
 * A scheme is Amber turned round the hue wheel. Every literal colour token
 * becomes `oklch(from <amber value> l c calc(h + var(--scheme-turn)))`, which
 * keeps its lightness and chroma, and so its contrast and its place in the
 * tone tiers, and keeps the small hue differences between tokens, since `h`
 * is the token's own. Amber is the absence of data-scheme: its tokens are the
 * hand-tuned originals, untouched. Everything rotated sits behind
 * @supports, so a browser without relative colour stays Amber rather than
 * meeting an invalid, transparent token.
 *
 * Pure black steps every dark tier down one: the page to black, raised
 * surfaces to what the page was, the highest to what dialogs were.
 *
 * Run with `pnpm run schemes` after changing a colour token in either file.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { SCHEME_TURNS as TURNS } from "../src/lib/theme"

/** Red stays red: an error isn't the theme. */
const KEEP = new Set(["--destructive"])

/** Pure black: each dark tier steps down one, keyed to the token it takes. */
const BLACK: Record<string, "black" | "--background" | "--dialog"> = {
  "--background": "black",
  "--card": "black",
  "--popover": "black",
  "--sidebar": "black",
  "--theme-color": "black",
  "--secondary": "--background",
  "--muted": "--background",
  "--accent": "--background",
  "--dialog": "--background",
  "--sidebar-accent": "--background",
  "--elevated": "--dialog",
  "--toast": "--dialog",
}

const tailwind = readFileSync("src/styles/tailwind.css", "utf8")
const m3 = readFileSync("src/styles/m3-colors.css", "utf8")

function block(css: string, selector: string): Map<string, string> {
  const start = css.indexOf(`${selector} {`)
  if (start < 0) throw new Error(`no ${selector} block`)
  const body = css.slice(start, css.indexOf("}", start))
  const tokens = new Map<string, string>()
  for (const [, name, value] of body.matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)) {
    tokens.set(name, value.trim())
  }
  return tokens
}

const isColour = (v: string) => /^(#[0-9a-f]{3,8}|rgba?\([^)]*\))$/i.test(v)
/** Black and white have no hue to turn. */
const isGrey = (v: string) => /^#(0{6}|f{6})$/i.test(v)
const turned = (v: string) =>
  `oklch(from ${v} l c calc(h + var(--scheme-turn)))`

const turns = ([name, value]: [string, string]) =>
  isColour(value) && !isGrey(value) && !KEEP.has(name)

function rotated(tokens: Map<string, string>): string {
  return [...tokens]
    .filter(turns)
    .map(([name, value]) => `    ${name}: ${turned(value)};`)
    .join("\n")
}

/**
 * Dark's turned tokens, plus dark's own value for any token light turns but
 * dark leaves alone: a reference such as --filled's var(--primary), or white.
 * The light scheme block outranks the plain dark block, so without restating
 * them dark would wear light's turned value: a dark label on a dark fill.
 */
function rotatedDark(
  light: Map<string, string>,
  dark: Map<string, string>
): string {
  return [...dark]
    .flatMap(([name, value]) => {
      if (turns([name, value])) return [`    ${name}: ${turned(value)};`]
      const lightValue = light.get(name)
      if (lightValue && turns([name, lightValue])) {
        return [`    ${name}: ${value};`]
      }
      return []
    })
    .join("\n")
}

const light = new Map([...block(tailwind, "\n:root"), ...block(m3, "\n:root")])
const dark = new Map([
  ...block(tailwind, '\n[data-theme="dark"]'),
  ...block(m3, '\n[data-theme="dark"]'),
])
const contrastLight = block(m3, "html:root")
const contrastDark = block(m3, 'html[data-theme="dark"]')

const black = Object.entries(BLACK).map(([name, from]) => {
  const value = from === "black" ? "#000000" : dark.get(from)
  if (!value) throw new Error(`no dark ${from}`)
  return [name, value] as const
})

const SUPPORTS = "@supports (color: oklch(from red l c h))"
const css = `/* Generated by scripts/schemes.ts (pnpm run schemes) from the Amber tokens
   in tailwind.css and m3-colors.css. Do not edit by hand. */

/* Unitless: inside oklch(from …), h is a number, and calc(h + 168deg)
   mixes a number with an angle, which makes the whole colour invalid. */
${Object.entries(TURNS)
  .map(
    ([scheme, turn]) =>
      `:root[data-scheme="${scheme}"] {\n  --scheme-turn: ${turn};\n}`
  )
  .join("\n\n")}

${SUPPORTS} {
  :root[data-scheme] {
${rotated(light)}
  }

  :root[data-scheme][data-theme="dark"] {
${rotatedDark(light, dark)}
  }
}

/* Pure black, in the dark theme only. Amber's values as they are; a scheme's turned below. */
:root[data-night="black"][data-theme="dark"] {
${black.map(([name, value]) => `  ${name}: ${value};`).join("\n")}
}

${SUPPORTS} {
  :root[data-scheme][data-night="black"][data-theme="dark"] {
${black
  .filter(([, value]) => !isGrey(value))
  .map(([name, value]) => `    ${name}: ${turned(value)};`)
  .join("\n")}
  }
}

/* More contrast: m3-colors.css's stronger set, turned as well. Last, so it
   wins over the plain scheme above at the same specificity. */
@media (prefers-contrast: more) {
  ${SUPPORTS} {
    :root[data-scheme] {
${rotated(contrastLight).replace(/^ {4}/gm, "      ")}
    }

    :root[data-scheme][data-theme="dark"] {
${rotatedDark(contrastLight, contrastDark).replace(/^ {4}/gm, "      ")}
    }
  }
}
`

writeFileSync("src/styles/schemes.css", css)
console.log(
  `schemes.css: ${Object.keys(TURNS).length} schemes, ${light.size} light and ${dark.size} dark tokens read`
)
