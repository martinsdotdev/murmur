/**
 * Generates src/styles/m3-colors.css: the Material 3 colour roles Murmur's own
 * palette lacks, and a stronger set for `prefers-contrast: more`.
 *
 * Murmur's Fluent-named hex values in tailwind.css stay the source of truth.
 * This only fills gaps: the 3:1 `outline` stroke, and stronger text, icon and
 * stroke colours for people who ask for more contrast. Surfaces never change,
 * which is how M3 applies its contrast levels.
 *
 * The scheme is Fidelity on the 2021 spec, seeded with the brand amber. Fidelity
 * keeps amber's hue and chroma (the Expressive variant turns it purple), and
 * Material Color Utilities forces Fidelity onto the 2021 spec on phones anyway.
 * The neutral palettes are pinned to the hue of Murmur's beige, because MCU's
 * default neutrals inherit the seed's orange and turn the cream peach.
 *
 * Run with `pnpm run tokens`. tsx rather than plain node: 0.4.0 has
 * extensionless relative imports that Node's ESM loader rejects.
 */
import { writeFileSync } from "node:fs"
import {
  DynamicScheme,
  Hct,
  TonalPalette,
  Variant,
  argbFromHex,
  hexFromArgb,
} from "@material/material-color-utilities"

const SEED = "#b86d20" // --primary
const BEIGE = "#ece4d2" // --secondary, neutral-background-3

const seed = Hct.fromInt(argbFromHex(SEED))
const beige = Hct.fromInt(argbFromHex(BEIGE))

function scheme(isDark: boolean, contrastLevel: number) {
  return new DynamicScheme({
    sourceColorHct: seed,
    variant: Variant.FIDELITY,
    contrastLevel,
    isDark,
    specVersion: "2021",
    platform: "phone",
    primaryPalette: TonalPalette.fromHueAndChroma(seed.hue, seed.chroma),
    secondaryPalette: TonalPalette.fromHueAndChroma(seed.hue, seed.chroma / 2),
    tertiaryPalette: TonalPalette.fromHueAndChroma(seed.hue + 60, 24),
    neutralPalette: TonalPalette.fromHueAndChroma(beige.hue, 6),
    neutralVariantPalette: TonalPalette.fromHueAndChroma(beige.hue, 10),
  })
}

const hex = (argb: number) => hexFromArgb(argb)

/** The roles Murmur has no value of its own for. */
function base(s: DynamicScheme) {
  return { "--md-outline": hex(s.outline) }
}

/**
 * M3's medium contrast level, applied to content and strokes only. Each Murmur
 * variable takes the role it plays. Medium rather than high: high takes both
 * text roles to pure black, which erases the gap between primary and muted
 * text, and medium already puts muted text past 10:1.
 */
function stronger(s: DynamicScheme) {
  return {
    "--foreground": hex(s.onSurface),
    "--muted-foreground": hex(s.onSurfaceVariant),
    "--brand": hex(s.primary),
    "--ring": hex(s.primary),
    "--md-outline": hex(s.outline),
    "--border": hex(s.outlineVariant),
    "--input": hex(s.outlineVariant),
    "--track": hex(s.outlineVariant),
  }
}

const block = (selector: string, vars: Record<string, string>, indent = "") =>
  `${indent}${selector} {\n` +
  Object.entries(vars)
    .map(([k, v]) => `${indent}  ${k}: ${v};`)
    .join("\n") +
  `\n${indent}}\n`

// The stronger selectors carry one more type selector than tailwind.css's
// `:root` and `[data-theme="dark"]`, because this file is imported ahead of
// those blocks and would otherwise lose to them.
const css =
  `/* Generated by scripts/m3-colors.ts (pnpm run tokens) from\n` +
  `   @material/material-color-utilities 0.4.0. Do not edit by hand. */\n\n` +
  block(":root", base(scheme(false, 0))) +
  "\n" +
  block('[data-theme="dark"]', base(scheme(true, 0))) +
  "\n@media (prefers-contrast: more) {\n" +
  block("html:root", stronger(scheme(false, 0.5)), "  ") +
  "\n" +
  block('html[data-theme="dark"]', stronger(scheme(true, 0.5)), "  ") +
  "}\n"

const out = new URL("../src/styles/m3-colors.css", import.meta.url)
writeFileSync(out, css.replace(/\n/g, "\r\n"))
